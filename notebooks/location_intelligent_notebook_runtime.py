"""Notebook execution guards. No counting policy, retrieval or inference here."""
from pathlib import Path
import importlib
import sys
import json
import hashlib

_STAGE_ORDER=['dependencies','configuration','bq_auth','sources','calculation','stores','allocation','output']
STAGES={name:{'status':'NOT_RUN'} for name in _STAGE_ORDER}
NOTEBOOK_REPORT_PATH=Path('/kaggle/working/results/area_coverage_market/notebook_readiness.json')


def save_notebook_readiness():
    report={'schema':'market_notebook_readiness_v1','stages':STAGES,
            'candidate_buildings':None,'status':'NOT_READY'}
    if STAGES['allocation']['status'] in {'SUCCEEDED','PARTIAL'}:
        result=globals().get('MARKET')
        if result:
            report['candidate_buildings']=result['summary']['candidate_whole_buildings']
            report['status']='PARTIAL' if result['status']=='PARTIAL' else 'SUCCEEDED'
    if STAGES['output']['status']=='FAILED':report['status']='EXPORT_FAILED'
    NOTEBOOK_REPORT_PATH.parent.mkdir(parents=True,exist_ok=True)
    tmp=NOTEBOOK_REPORT_PATH.with_suffix('.partial')
    tmp.write_text(json.dumps(report,indent=2));tmp.replace(NOTEBOOK_REPORT_PATH)
    return report


def begin_notebook_stage(name,required=()):
    index=_STAGE_ORDER.index(name)
    for following in _STAGE_ORDER[index:]:STAGES[following]={'status':'NOT_RUN'}
    if index<=_STAGE_ORDER.index('allocation'):globals()['MARKET']=None
    missing=[key for key in required if STAGES[key]['status'] not in {'SUCCEEDED','PARTIAL'}]
    if missing:
        STAGES[name]={'status':'BLOCKED','reason':'UPSTREAM_NOT_READY','required':missing}
        print(name+': BLOCKED — '+', '.join(missing));save_notebook_readiness();return False
    STAGES[name]={'status':'RUNNING'};return True


def finish_notebook_stage(name,status='SUCCEEDED'):
    STAGES[name]={'status':status};save_notebook_readiness()


def fail_notebook_stage(name,error):
    # No exception message/locals: credential values cannot enter this report.
    import traceback
    STAGES[name]={'status':'FAILED','error_type':type(error).__name__,
                  'trace':[{'file':Path(f.filename).name,'line':f.lineno,'function':f.name}
                           for f in traceback.extract_tb(error.__traceback__)[-5:]],
                  'action':'Inspect source readiness; retry failed stage after dependency/source recovery'}
    print(name+': FAILED ('+type(error).__name__+'). See notebook_readiness.json; no counts generated for missing inputs.')
    save_notebook_readiness()


def activate_notebook_sources(directory,expected):
    """Load exact written sources, even when a previous kernel imported old code."""
    directory=Path(directory).resolve()
    for name,digest in expected.items():
        file=directory/name
        if not file.is_file() or hashlib.sha256(file.read_bytes()).hexdigest()!=digest:
            raise RuntimeError('SOURCE_INSTALL_INCOMPLETE: run all implementation cells before configuration')
    # Python's timestamp/size .pyc validation alone is insufficient when writefile
    # replaces a module rapidly. Remove only this notebook's generated bytecode.
    for file in (directory/'__pycache__').glob('*.pyc'):file.unlink()
    for name in list(sys.modules):
        if name.startswith('location_intelligent_'):del sys.modules[name]
    sys.dont_write_bytecode=True
    sys.path[:]=[str(directory)]+[p for p in sys.path if p!=str(directory)]
    importlib.invalidate_caches()
    for name,apis in {'location_intelligent_map_poi':['load_optional_osm_pois'],
                      'location_intelligent_market_runtime':['acquire_market_network','build_market']}.items():
        module=importlib.import_module(name)
        if Path(module.__file__).resolve().parent!=directory:raise ImportError('Wrong notebook source location')
        if not all(callable(getattr(module,api,None)) for api in apis):raise ImportError('Incomplete notebook API')
